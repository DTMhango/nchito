/**
 * Generate src/lib/api/schema.d.ts from ../docs/openapi.json (`npm run gen:api`).
 *
 * A field with a default is optional when we send it, and FastAPI always serialises every
 * field of a response model. openapi-typescript has one switch for both, so before
 * generating we mark every property required in schemas that are only ever read (reachable
 * from a response and never from a request body or parameter), and generate with defaults
 * left optional. Schemas used both ways keep defaulted fields optional.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(here, "../../docs/openapi.json")
const target = resolve(here, "../src/lib/api/schema.d.ts")

const doc = JSON.parse(readFileSync(source, "utf8"))
const schemas = doc.components?.schemas ?? {}
const PREFIX = "#/components/schemas/"

function refsIn(node, out = new Set()) {
  if (Array.isArray(node)) node.forEach((n) => refsIn(n, out))
  else if (node && typeof node === "object") {
    if (typeof node.$ref === "string" && node.$ref.startsWith(PREFIX))
      out.add(node.$ref.slice(PREFIX.length))
    Object.values(node).forEach((n) => refsIn(n, out))
  }
  return out
}

function closure(roots) {
  const seen = new Set()
  const stack = [...roots]
  while (stack.length) {
    const name = stack.pop()
    if (seen.has(name) || !schemas[name]) continue
    seen.add(name)
    refsIn(schemas[name]).forEach((r) => stack.push(r))
  }
  return seen
}

const requestRoots = new Set()
const responseRoots = new Set()
for (const item of Object.values(doc.paths ?? {})) {
  for (const op of Object.values(item)) {
    if (!op || typeof op !== "object") continue
    refsIn(op.requestBody ?? {}, requestRoots)
    refsIn(op.parameters ?? [], requestRoots)
    refsIn(op.responses ?? {}, responseRoots)
  }
}
const written = closure(requestRoots)
const readOnly = [...closure(responseRoots)].filter((n) => !written.has(n))

for (const name of readOnly) {
  const s = schemas[name]
  if (!s?.properties) continue
  // A property the server leaves out when null (`x-omitted-when-null`) stays optional.
  s.required = Object.keys(s.properties).filter(
    (k) => !s.properties[k]["x-omitted-when-null"]
  )
}

const ast = await openapiTS(doc, { defaultNonNullable: false })
const header = `/**
 * This file was auto-generated by openapi-typescript (scripts/gen-api.mjs).
 * Do not make direct changes to the file. Run \`npm run gen:api\`.
 */

`
writeFileSync(target, header + astToString(ast))
console.log(
  `schema.d.ts: ${Object.keys(schemas).length} schemas, ${readOnly.length} response-only`
)
